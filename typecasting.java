public class typecasting 
{
    public static void main(String [] args)
    {
        int age = 12;
        // implicit typecasting 
        double d = age;
        System.out.println(d);

        //explicit typecasting 
        int  k = 123;
        double h = (int) k;
        System.out.println(h);
        short s = 1;
    }   
}
